"""Настройки бота. Под нового клиента обычно достаточно поменять только этот файл."""
import os
import sys

from dotenv import load_dotenv

# Секреты (токен) хранятся в файле .env, а не в коде, чтобы случайно не выложить их на GitHub.
load_dotenv()

BOT_TOKEN = os.getenv("BOT_TOKEN", "").strip()
if not BOT_TOKEN:
    sys.exit("Не найден BOT_TOKEN. Откройте файл .env и вставьте токен, полученный у @BotFather.")

try:
    # ID администратора, которому приходят уведомления о записях. 0 — уведомления выключены.
    ADMIN_ID = int(os.getenv("ADMIN_ID") or 0)
except ValueError:
    sys.exit("ADMIN_ID в файле .env должен быть числом. Узнать свой ID можно командой /myid в боте.")

